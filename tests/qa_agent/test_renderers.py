"""The renderers: every part of the case format, written for pytest and for REST Assured."""

from pathlib import Path

import pytest

from qa_agent.cases import parse_case_file
from qa_agent.renderers import RENDERERS, RenderError

EVERYTHING = {"feature": "Bookings", "cases": [{
    "id": "TC7", "title": "Everything the format can say, isn't it", "criteria": ["AC-1"], "priority": "P1",
    "tags": ["smoke", "crud-flow"], "data": "data/rows.csv",
    "steps": [
        {"request": {"method": "POST", "path": "/bookings",
                     "body": {"name": "Asha {{unique}}", "amount": "{{row.amount}}", "paid": True, "ids": [1, 2]}},
         "expect": {"status": "{{row.status}}", "types": {"pnr": "string"}}, "capture": {"pnr": "pnr"}},
        {"request": {"method": "GET", "path": "/bookings", "query": {"owner": "{{pnr}}"},
                     "headers": {"X-Trace": "t-{{unique}}"}},
         "expect": {"status": 200, "fields": {"items[0].pnr": "{{pnr}}"}, "exists": ["count"],
                    "contains": {"items[0].email": "@"}, "list_length": {"items": 1},
                    "list_contains": {"items": {"pnr": "{{pnr}}"}}, "list_excludes": {"items": {"status": "x"}},
                    "headers": {"content-type": "application/json"}, "within_ms": 2000}},
        {"request": {"method": "PUT", "path": "/bookings/{{pnr}}", "query": {"notify": "no"}, "body": {"a": 1}},
         "expect": {"status": 200}},
        {"request": {"method": "GET", "path": "/health-check", "service": "notifications", "auth": "none"},
         "expect": {"status": 200}}]}]}


def cases(data=EVERYTHING):
    case_file = parse_case_file(data, Path("cases/bookings.yaml"))
    return case_file, case_file.cases


def test_pytest_code_is_valid_python_and_uses_the_framework_as_a_person_would():
    case_file, found = cases()
    generated = RENDERERS["python"].render_file("cases/bookings.yaml", case_file, found)
    compile(generated.text, generated.path, "exec")
    assert generated.path == "tests/generated/test_bookings.py"
    text = generated.text
    assert text.startswith("# Generated by qa-agent from cases/bookings.yaml. Do not edit")
    assert "TC7_ROWS = load_rows(PROJECT / \"data/rows.csv\")" in text
    assert "def test_tc7_everything_the_format_can_say_isnt_it(api, context, api_for, row):" in text
    for line in ('@pytest.mark.smoke', '@pytest.mark.crud_flow', '@pytest.mark.writes', '@pytest.mark.case("TC7")',
                 'unique = unique_id()', '"name": f"Asha {unique}"', '"amount": row["amount"]',
                 'Expect(response).status_is(row["status"])', 'context.remember("pnr", response.value("pnr"))',
                 'params={"owner": context.get("pnr")}, headers={"X-Trace": f"t-{unique}"}',
                 '.list_contains("items", **{"pnr": context.get("pnr")})', '.responded_within(2000))',
                 'api.request("PUT", f"/bookings/{context.get(\'pnr\')}", json={"a": 1}, params={"notify": "no"})',
                 'api_for("notifications").without_auth().get("/health-check")'):
        assert line in text, line


def test_rest_assured_code_uses_the_framework_as_a_person_would():
    case_file, found = cases()
    generated = RENDERERS["restassured"].render_file("cases/bookings.yaml", case_file, found)
    text = generated.text
    assert generated.path == "src/test/java/generated/BookingsTest.java"
    assert "public class BookingsTest extends BaseTest {" in text
    assert '@Test(groups = {"functional", "smoke", "crud-flow", "writes"}, dataProvider = "tc7EverythingTheFormat' in text
    for line in ("public void tc7EverythingTheFormatCanSayIsntIt(Map<String, Object> row) {",
                 'String unique = TestData.uniqueId();', '"name", "Asha " + unique', '"amount", row.get("amount")',
                 '"ids", List.of(1, 2)', 'statusIs(((Number) row.get("status")).intValue())',
                 'api().get("/bookings", Map.of("owner", context().get("pnr")), Map.of("X-Trace", "t-" + unique))',
                 '.listContains("items", "pnr", context().get("pnr"))', '.respondedWithin(2000);',
                 'api().request("PUT", "/bookings/" + context().get("pnr"), Map.of("a", 1), Map.of("notify", "no"), Map.of())',
                 'apiFor("notifications").withoutAuth().get("/health-check")', "import java.util.List;"):
        assert line in text, line


def test_java_gets_a_string_join_when_two_values_meet_and_map_of_entries_past_ten():
    data = {"feature": "x", "cases": [{"id": "TC1", "title": "t", "steps": [
        {"request": {"method": "POST", "path": "/x/{{a}}{{b}}", "body": {f"k{n}": n for n in range(11)}},
         "expect": {"status": 201}}]}]}
    case_file, found = cases(data)
    text = RENDERERS["restassured"].render_file("cases/x.yaml", case_file, found).text
    assert '"/x/" + context().get("a") + context().get("b")' in text
    assert "Map.ofEntries(" in text and 'Map.entry("k10", 10)' in text
    data["cases"][0]["steps"][0]["request"]["headers"] = {"X-Pair": "{{a}}{{b}}"}
    case_file, found = cases(data)
    assert 'Map.of("X-Pair", "" + context().get("a") + context().get("b"))' in \
        RENDERERS["restassured"].render_file("cases/x.yaml", case_file, found).text


def test_a_null_in_a_body_is_refused_for_java_with_the_reason():
    data = {"feature": "x", "cases": [{"id": "TC1", "title": "t", "steps": [
        {"request": {"method": "POST", "path": "/x", "body": {"email": None}}, "expect": {"status": 422}}]}]}
    case_file, found = cases(data)
    with pytest.raises(RenderError, match="TC1 step 1: a null value"):
        RENDERERS["restassured"].render_file("cases/x.yaml", case_file, found)
    compile(RENDERERS["python"].render_file("cases/x.yaml", case_file, found).text, "x", "exec")


def test_the_markers_file_registers_the_teams_tags():
    _, found = cases()
    conftest = RENDERERS["python"].support_files(found)[0]
    assert conftest.path == "tests/generated/conftest.py"
    assert 'TAGS = ["crud_flow"]' in conftest.text                   # smoke is built in
    compile(conftest.text, conftest.path, "exec")


