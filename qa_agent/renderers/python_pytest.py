"""Approved cases -> pytest tests on api_test_framework: tests/generated/test_<case file>.py.

    @pytest.mark.functional
    @pytest.mark.writes
    @pytest.mark.case("TC003")
    @pytest.mark.priority("P1")
    def test_tc003_a_second_cancel_is_refused(api, context):
        unique = unique_id()
        # 1. POST /bookings
        response = api.post("/bookings", json={"passenger_name": f"Asha Rao {unique}", ...})
        Expect(response).status_is(201)
        context.remember("pnr", response.value("pnr"))
"""

import json
import re
from typing import Any

from qa_agent.cases import Case, CaseFile, Step
from qa_agent.renderers.common import (BUILT_IN_MARKERS, HEADER, TEMPLATES, GeneratedFile, Literal, Uses,
                                       file_slug, groups, id_slug, parts, title_words)

OUTPUT_DIR = "tests/generated"
LINE = 110


class PytestRenderer:
    stack = "python"
    output_dir = OUTPUT_DIR
    header_mark = "# Generated by qa-agent"

    def test_names(self, case: Case) -> list[str]:
        return [f"test_{id_slug(case)}_" + "_".join(title_words(case))]

    def render_file(self, source: str, case_file: CaseFile, cases: list[Case]) -> GeneratedFile:
        tests, imports, data_files = [], {"Expect"}, []
        for case in cases:
            text, uses = self._test(case)
            tests.append(text)
            if uses.unique:
                imports.add("unique_id")
            if case.data:
                imports.add("load_rows")
                data_files.append((_rows_name(case), case.data))
        text = TEMPLATES.get_template("test_module.py.j2").render(
            header=HEADER.format(source=source), feature=case_file.feature, tests=tests,
            imports=sorted(imports), data_files=data_files)
        return GeneratedFile(f"{OUTPUT_DIR}/test_{file_slug(case_file.path.stem)}.py", text)

    def support_files(self, cases: list[Case]) -> list[GeneratedFile]:
        tags = sorted({_marker(tag) for case in cases for tag in case.tags} - set(BUILT_IN_MARKERS))
        text = TEMPLATES.get_template("markers_conftest.py.j2").render(tags=tags)
        return [GeneratedFile(f"{OUTPUT_DIR}/conftest.py", text)]

    def _test(self, case: Case) -> tuple[str, Uses]:
        uses = Uses()
        body = []
        for number, step in enumerate(case.steps, start=1):
            body += self._step(number, step, uses)
        lines = [f"@pytest.mark.{_marker(group)}" for group in groups(case)]
        lines += [f'@pytest.mark.case("{case.id}")', f'@pytest.mark.priority("{case.priority}")']
        arguments = ["api", "context"] + (["api_for"] if uses.services else [])
        if case.data:
            rows = _rows_name(case)
            lines.append(f'@pytest.mark.parametrize("row", {rows}, ids=lambda row: str(row["case"]) if "case" in row '
                         f"else None)")
            arguments.append("row")
        lines.append(f"def {self.test_names(case)[0]}({', '.join(arguments)}):")
        criteria = f" Criteria: {', '.join(case.criteria)}." if case.criteria else ""
        lines.append(f'    """{_docstring(case.title)}.{criteria}"""')
        if uses.unique:
            lines.append("    unique = unique_id()")
        return "\n".join(lines + body), uses

    def _step(self, number: int, step: Step, uses: Uses) -> list[str]:
        request = step.request
        lines = [f"    # {number}. {request.method} {request.path}" + (f": {step.name}" if step.name else "")]
        client = f'api_for("{request.service}")' if request.service else "api"
        if request.service:
            uses.services.add(request.service)
        if request.auth == "none":
            client += ".without_auth()"
        path = _code(request.path, uses)
        named = []
        if request.body is not None:
            named.append(("json", request.body))
        if request.query:
            named.append(("params", request.query))
        if request.headers:
            named.append(("headers", request.headers))
        keys = [key for key, _ in named]
        if _fits_shortcut(request.method, keys):
            call = f"{client}.{request.method.lower()}({path}"
        else:
            call = f'{client}.request("{request.method}", {path}'
        prefix = "    response = "
        rendered = [f"{key}={_code(value, uses)}" for key, value in named]
        one_line = prefix + call + "".join(", " + item for item in rendered) + ")"
        if len(one_line) <= LINE:
            lines.append(one_line)
        else:
            lines.append(prefix + call + "".join(", " + f"{key}={_code(value, uses, 1)}" for key, value in named) + ")")
        if step.expect:
            lines += _expect_lines(step.expect, uses)
        for name, response_path in step.capture.items():
            lines.append(f'    context.remember("{name}", response.value({json.dumps(response_path)}))')
        return lines


def _fits_shortcut(method: str, keys: list[str]) -> bool:
    """api.get(path, params, headers) · post(path, json, params, headers) · put/patch(path, json, headers) ·
    delete(path, headers); anything else goes through api.request(...)."""
    allowed = {"GET": {"params", "headers"}, "POST": {"json", "params", "headers"}, "PUT": {"json", "headers"},
               "PATCH": {"json", "headers"}, "DELETE": {"headers"}}[method]
    return set(keys) <= allowed


def _expect_lines(expect: dict, uses: Uses) -> list[str]:
    calls = []
    if "status" in expect:
        calls.append(f"status_is({_code(expect['status'], uses)})")
    for path, value in expect.get("fields", {}).items():
        calls.append(f"field_equals({json.dumps(path)}, {_code(value, uses)})")
    for path in expect.get("exists", []):
        calls.append(f"field_exists({json.dumps(path)})")
    for path, kind in expect.get("types", {}).items():
        calls.append(f"field_is_type({json.dumps(path)}, {json.dumps(kind)})")
    for path, text in expect.get("contains", {}).items():
        calls.append(f"field_contains({json.dumps(path)}, {_code(text, uses)})")
    for path, count in expect.get("list_length", {}).items():
        calls.append(f"list_length({json.dumps(path)}, {count})")
    for key, method in (("list_contains", "list_contains"), ("list_excludes", "list_excludes")):
        for path, match in expect.get(key, {}).items():
            calls.append(f"{method}({json.dumps(path)}, **{_code(match, uses)})")
    for name, value in expect.get("headers", {}).items():
        calls.append(f"header_equals({json.dumps(name)}, {_code(value, uses)})")
    if "within_ms" in expect:
        calls.append(f"responded_within({expect['within_ms']})")
    one_line = "    Expect(response)." + ".".join(calls)
    if len(one_line) <= LINE or len(calls) == 1:
        return [one_line]
    return ["    (Expect(response)." + calls[0]] + [f"        .{call}" for call in calls[1:-1]] + \
        [f"        .{calls[-1]})"]


def _code(value: Any, uses: Uses, depth: int = 0) -> str:
    """A value from a case as Python code. depth > 0 writes a long mapping one key per line."""
    if isinstance(value, str):
        return _string(value, uses)
    if isinstance(value, bool) or value is None:
        return repr(value)
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, list):
        return "[" + ", ".join(_code(item, uses) for item in value) + "]"
    items = [f"{json.dumps(str(key))}: {_code(item, uses)}" for key, item in value.items()]
    flat = "{" + ", ".join(items) + "}"
    if depth == 0 or len(flat) <= LINE - 40:
        return flat
    indent = "    " * (depth + 1)
    return "{\n" + "".join(f"{indent}{item},\n" for item in items) + "    " * depth + "}"


def _string(text: str, uses: Uses) -> str:
    found = parts(text, uses)
    if len(found) == 1 and not isinstance(found[0], Literal):
        return _value_code(found[0])
    if all(isinstance(part, Literal) for part in found):
        return json.dumps(text)
    pieces = []
    for part in found:
        if isinstance(part, Literal):
            pieces.append(json.dumps(part.text)[1:-1].replace("{", "{{").replace("}", "}}"))
        else:
            pieces.append("{" + _value_code(part, quote="'") + "}")
    return 'f"' + "".join(pieces) + '"'


def _value_code(part, quote: str = '"') -> str:
    if part.kind == "unique":
        return "unique"
    if part.kind == "row":
        return f"row[{quote}{part.name}{quote}]"
    return f"context.get({quote}{part.name}{quote})"


def _rows_name(case: Case) -> str:
    return f"{re.sub(r'[^A-Z0-9]+', '_', case.id.upper()).strip('_')}_ROWS"


def _marker(tag: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]+", "_", tag).strip("_") or "tag"


def _docstring(title: str) -> str:
    return title.replace("\\", "\\\\").replace('"""', "'''").rstrip(".")
