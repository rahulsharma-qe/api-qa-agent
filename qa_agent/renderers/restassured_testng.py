"""Approved cases -> TestNG tests on restassured-api-framework: src/test/java/generated/<CaseFile>Test.java.

    @Test(groups = {"functional", "writes"})
    @CaseId("TC003") @Priority("P1")
    public void tc003ASecondCancelIsRefused() {
        String unique = TestData.uniqueId();
        ApiResponse response;
        // 1. POST /bookings
        response = api().post("/bookings", Map.of("passenger_name", "Asha Rao " + unique, ...));
        Expect.that(response).statusIs(201);
        context().remember("pnr", response.value("pnr"));
    }
"""

import json
from typing import Any

from qa_agent.cases import Case, CaseFile, Step
from qa_agent.renderers.common import (HEADER, TEMPLATES, GeneratedFile, Literal, RenderError, Uses, groups, id_slug,
                                       parts, title_words)

OUTPUT_DIR = "src/test/java/generated"
MAP_OF_LIMIT = 10                    # Map.of takes up to 10 pairs; more use Map.ofEntries
LINE = 120


class RestAssuredRenderer:
    stack = "restassured"
    output_dir = OUTPUT_DIR
    header_mark = "// Generated by qa-agent"

    def test_names(self, case: Case) -> list[str]:
        return [id_slug(case).replace("_", "") + "".join(word.capitalize() for word in title_words(case))]

    def class_name(self, case_file: CaseFile) -> str:
        words = [word for word in "".join(c if c.isalnum() else " " for c in case_file.path.stem).split() if word]
        name = "".join(word[0].upper() + word[1:] for word in words) or "Cases"
        return (name if name[0].isalpha() else "Cases" + name) + "Test"

    def render_file(self, source: str, case_file: CaseFile, cases: list[Case]) -> GeneratedFile:
        methods, needs = [], set()
        for case in cases:
            text, used = self._method(case)
            methods.append(text)
            needs |= used
        class_name = self.class_name(case_file)
        text = TEMPLATES.get_template("TestClass.java.j2").render(
            header=HEADER.format(source=source), feature=case_file.feature, class_name=class_name,
            methods=methods, import_groups=_imports(needs))
        return GeneratedFile(f"{OUTPUT_DIR}/{class_name}.java", text)

    def support_files(self, cases: list[Case]) -> list[GeneratedFile]:
        return []

    def _method(self, case: Case) -> tuple[str, set]:
        uses, needs = Uses(), {"ApiResponse", "Expect"}
        body = []
        for number, step in enumerate(case.steps, start=1):
            body += self._step(case, number, step, uses, needs)
        name = self.test_names(case)[0]
        lines = []
        group_list = ", ".join(json.dumps(group) for group in groups(case))
        test = f"groups = {{{group_list}}}"
        if case.data:
            provider = f"{name}Rows"
            test += f', dataProvider = "{provider}"'
            needs |= {"DataProvider", "TestData", "Map"}
            lines += ["    /** One run per row of " + case.data + ". */",
                      f'    @DataProvider(name = "{provider}")',
                      f"    public Object[][] {provider}() {{",
                      f"        return TestData.asDataProvider(TestData.rows({json.dumps(case.data)}));",
                      "    }", ""]
        criteria = f" Criteria: {', '.join(case.criteria)}." if case.criteria else ""
        lines += [f"    /** {_comment(case.title)}.{criteria} */",
                  f"    @Test({test})",
                  f"    @CaseId({json.dumps(case.id)}) @Priority({json.dumps(case.priority)})",
                  f"    public void {name}({'Map<String, Object> row' if case.data else ''}) {{"]
        if uses.unique:
            lines.append("        String unique = TestData.uniqueId();")
            needs.add("TestData")
        lines.append("        ApiResponse response;")
        lines += body
        lines.append("    }")
        return "\n".join(lines), needs

    def _step(self, case: Case, number: int, step: Step, uses: Uses, needs: set) -> list[str]:
        request = step.request
        where = f"{case.id} step {number}"
        lines = [f"        // {number}. {request.method} {request.path}" + (f": {step.name}" if step.name else "")]
        client = f"apiFor({json.dumps(request.service)})" if request.service else "api()"
        if request.auth == "none":
            client += ".withoutAuth()"
        path = _string(request.path, uses)
        body = _code(request.body, uses, needs, where, wrap=True) if request.body is not None else "null"
        params = _code(request.query, uses, needs, where) if request.query else None
        headers = _string_map(request.headers, uses, needs) if request.headers else None
        method = request.method
        if method == "GET" and not headers:
            call = f"{client}.get({path}" + (f", {params})" if params else ")")
        elif method == "GET":
            call = f"{client}.get({path}, {params or 'Map.of()'}, {headers})"
        elif method == "POST" and not params:
            call = f"{client}.post({path}, {body}" + (f", {headers})" if headers else ")")
        elif method in ("PUT", "PATCH") and not params and not headers:
            call = f"{client}.{method.lower()}({path}, {body})"
        elif method == "DELETE" and not params and not headers and request.body is None:
            call = f"{client}.delete({path})"
        else:
            call = f'{client}.request("{method}", {path}, {body}, {params or "Map.of()"}, {headers or "Map.of()"})'
        if "Map.of()" in call:
            needs.add("Map")
        lines.append(f"        response = {call};")
        if step.expect:
            lines += _expect_lines(step.expect, uses, needs, where)
        for name, response_path in step.capture.items():
            lines.append(f'        context().remember("{name}", response.value({json.dumps(response_path)}));')
        return lines


def _expect_lines(expect: dict, uses: Uses, needs: set, where: str) -> list[str]:
    calls = []
    if "status" in expect:
        status = expect["status"]
        calls.append(f"statusIs({status})" if isinstance(status, int)
                     else f"statusIs(((Number) {_string(status, uses)}).intValue())")
    for path, value in expect.get("fields", {}).items():
        calls.append(f"fieldEquals({json.dumps(path)}, {_code(value, uses, needs, where)})")
    for path in expect.get("exists", []):
        calls.append(f"fieldExists({json.dumps(path)})")
    for path, kind in expect.get("types", {}).items():
        calls.append(f"fieldIsType({json.dumps(path)}, {json.dumps(kind)})")
    for path, text in expect.get("contains", {}).items():
        calls.append(f"fieldContains({json.dumps(path)}, {_as_string(text, uses)})")
    for path, count in expect.get("list_length", {}).items():
        calls.append(f"listLength({json.dumps(path)}, {count})")
    for key, method in (("list_contains", "listContains"), ("list_excludes", "listExcludes")):
        for path, match in expect.get(key, {}).items():
            pairs = ", ".join(f"{json.dumps(str(k))}, {_code(v, uses, needs, where)}" for k, v in match.items())
            calls.append(f"{method}({json.dumps(path)}, {pairs})")
    for name, value in expect.get("headers", {}).items():
        calls.append(f"headerEquals({json.dumps(name)}, {_as_string(value, uses)})")
    if "within_ms" in expect:
        calls.append(f"respondedWithin({expect['within_ms']})")
    one_line = "        Expect.that(response)." + ".".join(calls) + ";"
    if len(one_line) <= LINE or len(calls) == 1:
        return [one_line]
    return ["        Expect.that(response)." + calls[0]] + [f"                .{call}" for call in calls[1:-1]] + \
        [f"                .{calls[-1]};"]


def _code(value: Any, uses: Uses, needs: set, where: str, wrap: bool = False) -> str:
    """A value from a case as Java: Map.of, List.of, strings, numbers, true/false. wrap writes a long
    request body one field per line."""
    if value is None:
        raise RenderError(f"{where}: a null value can't be written in Java's Map.of; leave the field out, "
                          f"or use a value")
    if isinstance(value, str):
        return _string(value, uses)
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, list):
        needs.add("List")
        return "List.of(" + ", ".join(_code(item, uses, needs, where) for item in value) + ")"
    needs.add("Map")
    items = [(json.dumps(str(key)), _code(item, uses, needs, where)) for key, item in value.items()]
    if len(items) <= MAP_OF_LIMIT:
        entries, opening = [f"{key}, {item}" for key, item in items], "Map.of("
    else:
        entries, opening = [f"Map.entry({key}, {item})" for key, item in items], "Map.ofEntries("
    flat = opening + ", ".join(entries) + ")"
    if not wrap or len(flat) <= LINE - 60:
        return flat
    return opening + "\n" + ",\n".join(f"                {entry}" for entry in entries) + ")"


def _string_map(value: dict, uses: Uses, needs: set) -> str:
    """Headers: Map<String, String>, so every value is a String."""
    needs.add("Map")
    return "Map.of(" + ", ".join(f"{json.dumps(str(k))}, {_as_string(v, uses)}" for k, v in value.items()) + ")"


def _as_string(value: Any, uses: Uses) -> str:
    code = _string(str(value), uses)
    return code if code.startswith('"') or " + " in code else f"String.valueOf({code})"


def _string(text: str, uses: Uses) -> str:
    found = parts(text, uses)
    if len(found) == 1 and not isinstance(found[0], Literal):
        return _value_code(found[0])
    code = " + ".join(json.dumps(part.text) if isinstance(part, Literal) else _value_code(part) for part in found)
    if len(found) > 1 and not isinstance(found[0], Literal) and not isinstance(found[1], Literal):
        code = '"" + ' + code                  # two values side by side: make the + a string join
    return code or '""'


def _value_code(part) -> str:
    if part.kind == "unique":
        return "unique"
    if part.kind == "row":
        return f'row.get("{part.name}")'
    return f'context().get("{part.name}")'


def _imports(needs: set) -> list[list[str]]:
    java = [f"java.util.{name}" for name in ("List", "Map") if name in needs]
    testng = ["org.testng.annotations.DataProvider"] if "DataProvider" in needs else []
    testng.append("org.testng.annotations.Test")
    framework = ["apiqa.framework.client.ApiResponse"]
    if "TestData" in needs:
        framework.append("apiqa.framework.data.TestData")
    framework += ["apiqa.framework.expect.Expect", "apiqa.framework.testng.BaseTest",
                  "apiqa.framework.testng.CaseId", "apiqa.framework.testng.Priority"]
    return [group for group in (java, testng, framework) if group]


def _comment(title: str) -> str:
    return title.replace("*/", "* /").rstrip(".")
